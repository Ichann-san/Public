def write_clean_csv(output_path="data.csv"):
    n = 233
    assert len(time_vals) == n, f"Time has {len(time_vals)} values, expected {n}"
    assert len(current_vals) == n, f"Current has {len(current_vals)} values, expected {n}"
    assert len(voltage_vals) == n, f"Voltage has {len(voltage_vals)} values, expected {n}"
    assert len(relay_vals) == n, f"Relay has {len(relay_vals)} values, expected {n}"
    assert len(vsource_vals) == n, f"VSource has {len(vsource_vals)} values, expected {n}"
    assert len(flux_vals) == n, f"Flux has {len(flux_vals)} values, expected {n}"
    
    with open(output_path, 'w', newline='') as f:
        f.write("Index,Time_s,Current_A,Voltage_V,Relay,Voltage_source,Magnetic_flux_Vs\n")
        for i in range(n):
            row = [
                str(i + 1),
                f"{time_vals[i]:.15g}",
                f"{current_vals[i]:.4f}",
                f"{voltage_vals[i]:.4f}",
                str(relay_vals[i]),
                str(vsource_vals[i]),
                f"{flux_vals[i]:.15g}",
            ]
            f.write(','.join(row) + '\n')
    
    print(f"Clean CSV written to: {output_path}")
    print(f"Total rows: {n}")



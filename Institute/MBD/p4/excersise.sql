-- q1
SELECT r.CUSTOMERNAME
FROM RECEIPT r
JOIN DETAILITEM d ON r.RECEIPTNO = d.RECEIPTNO
JOIN ALBUM a ON d.ALBUMNO = a.ALBUMNO
WHERE a.RELEASEYEAR IN (2016, 2021)
GROUP BY r.CUSTOMERNAME
HAVING COUNT(DISTINCT a.RELEASEYEAR) = 2;

-- q2
SELECT DISTINCT s.SINGERNAME
FROM SINGER s
JOIN ALBUM a ON s.SINGERID = a.SINGERID
WHERE a.RELEASEYEAR < (
    SELECT RELEASEYEAR
    FROM ALBUM
    WHERE ALBUMNAME = 'LYODRA'
);

-- q3
SELECT DISTINCT s.SINGERNAME
FROM SINGER s
JOIN ALBUM a ON s.SINGERID = a.SINGERID
WHERE s.SINGERNAME != 'TULUS'
  AND a.PRICE > ANY (
      SELECT a2.PRICE
      FROM ALBUM a2
      JOIN SINGER s2 ON a2.SINGERID = s2.SINGERID
      WHERE s2.SINGERNAME = 'TULUS'
);

-- q4
SELECT r.CUSTOMERNAME, ROUND(SUM(d.TOTALPRICE), 1) AS total
FROM RECEIPT r
JOIN DETAILITEM d ON r.RECEIPTNO = d.RECEIPTNO
GROUP BY r.CUSTOMERNAME;

-- q5
SELECT ROUND(
    (SELECT SUM(d.AMOUNT)
     FROM DETAILITEM d
     JOIN ALBUM a ON d.ALBUMNO = a.ALBUMNO
     JOIN SINGER s ON a.SINGERID = s.SINGERID
     WHERE s.SINGERNAME = 'TULUS') * 100.0 / SUM(AMOUNT), 2
) AS percentage
FROM DETAILITEM;


CREATE DATABASE mbd4;

-- DDL
CREATE TABLE SINGER (
    SINGERID VARCHAR(10) PRIMARY KEY,
    SINGERNAME VARCHAR(50)
);

CREATE TABLE ALBUM (
    ALBUMNO VARCHAR(10) PRIMARY KEY,
    SINGERID VARCHAR(10),
    ALBUMNAME VARCHAR(50),
    RELEASEYEAR INT,
    PRICE NUMERIC(10, 2),
    FOREIGN KEY (SINGERID) REFERENCES SINGER(SINGERID)
);

CREATE TABLE RECEIPT (
    RECEIPTNO VARCHAR(10) PRIMARY KEY,
    CUSTOMERNAME VARCHAR(50),
    RECEIPTDATE DATE
);

CREATE TABLE DETAILITEM (
    DETAILID VARCHAR(10) PRIMARY KEY,
    ALBUMNO VARCHAR(10),
    RECEIPTNO VARCHAR(10),
    AMOUNT INT,
    TOTALPRICE NUMERIC(10, 2),
    FOREIGN KEY (ALBUMNO) REFERENCES ALBUM(ALBUMNO),
    FOREIGN KEY (RECEIPTNO) REFERENCES RECEIPT(RECEIPTNO)
);


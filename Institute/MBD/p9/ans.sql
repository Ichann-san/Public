-- Tabel SINGER
CREATE TABLE SINGER (
    SINGERID VARCHAR(10) PRIMARY KEY,
    SINGERNAME VARCHAR(50)
);

-- Tabel ALBUM
CREATE TABLE ALBUM (
    ALBUMNO VARCHAR(10) PRIMARY KEY,
    SINGERID VARCHAR(10) REFERENCES SINGER(SINGERID),
    ALBUMNAME VARCHAR(100),
    RELEASEYEAR INT,
    PRICE NUMERIC(15, 2)
);

-- Tabel RECEIPT
CREATE TABLE RECEIPT (
    RECEIPTNO VARCHAR(10) PRIMARY KEY,
    CUSTOMERNAME VARCHAR(100),
    RECEIPTDATE DATE
);

-- Tabel DETAILITEM
CREATE TABLE DETAILITEM (
    DETAILID VARCHAR(10) PRIMARY KEY,
    ALBUMNO VARCHAR(10) REFERENCES ALBUM(ALBUMNO),
    RECEIPTNO VARCHAR(10) REFERENCES RECEIPT(RECEIPTNO),
    AMOUNT INT,
    TOTALPRICE NUMERIC(15, 2)
);


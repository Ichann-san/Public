ALTER TABLE DETAILITEM 
ADD COLUMN TAX NUMERIC(15,2), 
ADD COLUMN NETPRICE NUMERIC(15,2);

UPDATE DETAILITEM 
SET TAX = CASE 
    WHEN TOTALPRICE >= 100000.00 THEN TOTALPRICE * 0.12 
    ELSE 0.00 
END;

UPDATE DETAILITEM 
SET NETPRICE = TOTALPRICE + TAX;



CREATE DATABASE pertemuan3

-- Create Tables
CREATE TABLE SINGER (
    SINGERID INTEGER PRIMARY KEY,
    SINGERNAME VARCHAR(50)
);

CREATE TABLE ALBUM (
    ALBUMNO CHARACTER(3) PRIMARY KEY,
    SINGERID INTEGER,
    ALBUMNAME VARCHAR(50),
    RELEASEYEAR INTEGER,
    PRICE NUMERIC(15,2),
    FOREIGN KEY (SINGERID) REFERENCES SINGER(SINGERID)
);

CREATE TABLE RECEIPT (
    RECEIPTNO CHARACTER(5) PRIMARY KEY,
    CUSTOMERNAME CHARACTER VARYING(20),
    RECEIPTDATE DATE
);

CREATE TABLE DETAILITEM (
    DETAILID CHARACTER(5) PRIMARY KEY,
    ALBUMNO CHARACTER(3),
    RECEIPTNO CHARACTER(5),
    AMOUNT INTEGER,
    TOTALPRICE NUMERIC(15,2),
    FOREIGN KEY (ALBUMNO) REFERENCES ALBUM(ALBUMNO),
    FOREIGN KEY (RECEIPTNO) REFERENCES RECEIPT(RECEIPTNO)
);


-- 1. DDL: CREATE TABLES
-- TABLE: Kategori
CREATE TABLE kategori (
    id_kategori CHAR(7) PRIMARY KEY,
    nama_kategori VARCHAR(100) NOT NULL
);

-- TABLE: Kantin
CREATE TABLE kantin (
    id_kantin CHAR(7) PRIMARY KEY,
    nama VARCHAR(50) NOT NULL,
    alamat VARCHAR(100) NOT NULL,
    rating DECIMAL(3,2) NOT NULL
);

-- TABLE: Pengguna
CREATE TABLE pengguna (
    id_pengguna CHAR(7) PRIMARY KEY,
    nama VARCHAR(50) NOT NULL,
    email VARCHAR(100) NOT NULL UNIQUE,
    password VARCHAR(100) NOT NULL,
    no_telp VARCHAR(15) NOT NULL,
    peran VARCHAR(20) NOT NULL,
    id_kantin CHAR(7),

    CONSTRAINT fk_pengguna_kantin
        FOREIGN KEY (id_kantin)
        REFERENCES kantin(id_kantin)
        ON DELETE SET NULL
);

-- TABLE: Produk
CREATE TABLE produk (
    id_produk CHAR(7) PRIMARY KEY,
    nama VARCHAR(100) NOT NULL,
    stok INTEGER NOT NULL,
    harga NUMERIC(12,2) NOT NULL,
    tanggal_produksi TIMESTAMP NOT NULL,
    tanggal_kedaluwarsa TIMESTAMP NOT NULL,

    id_kantin CHAR(7) NOT NULL,
    id_kategori CHAR(7) NOT NULL,

    CONSTRAINT fk_produk_kantin
        FOREIGN KEY (id_kantin)
        REFERENCES kantin(id_kantin)
        ON DELETE CASCADE,

    CONSTRAINT fk_produk_kategori
        FOREIGN KEY (id_kategori)
        REFERENCES kategori(id_kategori)
        ON DELETE RESTRICT
);

-- TABLE: Pesanan
CREATE TABLE pesanan (
    id_pesanan CHAR(7) PRIMARY KEY,
    timestamp TIMESTAMP NOT NULL,
    total_harga NUMERIC(12,2) NOT NULL,
    status VARCHAR(30) NOT NULL,

    id_pengguna CHAR(7) NOT NULL,

    CONSTRAINT fk_pesanan_pengguna
        FOREIGN KEY (id_pengguna)
        REFERENCES pengguna(id_pengguna)
        ON DELETE CASCADE
);

-- TABLE: Detail_Pesanan
CREATE TABLE detail_pesanan (
    id_pesanan CHAR(7),
    id_produk CHAR(7),
    jumlah INTEGER NOT NULL,
    subtotal NUMERIC(12,2) NOT NULL,

    PRIMARY KEY (id_pesanan, id_produk),

    CONSTRAINT fk_detail_pesanan
        FOREIGN KEY (id_pesanan)
        REFERENCES pesanan(id_pesanan)
        ON DELETE CASCADE,

    CONSTRAINT fk_detail_produk
        FOREIGN KEY (id_produk)
        REFERENCES produk(id_produk)
        ON DELETE CASCADE
);

-- TABLE: Ulasan
CREATE TABLE ulasan (
    id_ulasan CHAR(7) PRIMARY KEY,
    nilai_rating INTEGER NOT NULL,
    teks_komentar TEXT NOT NULL,

    id_pesanan CHAR(7) NOT NULL UNIQUE,

    CONSTRAINT fk_ulasan_pesanan
        FOREIGN KEY (id_pesanan)
        REFERENCES pesanan(id_pesanan)
        ON DELETE CASCADE
);

